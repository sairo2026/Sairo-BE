-- expiry_task: 계약 기준 복합 FK로 재구성한 D-90 계약 후속 업무. 전세·월세에만 생성한다.
CREATE TABLE expiry_task (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    office_id               BIGINT      NOT NULL,
    property_id             BIGINT      NOT NULL,
    property_contract_id    BIGINT      NOT NULL,
    deal_type               VARCHAR(10) NOT NULL CHECK (deal_type IN ('JEONSE','MONTHLY')),
    task_type               VARCHAR(10) NOT NULL DEFAULT 'D90',
    contract_end_date       DATE        NOT NULL,
    target_date             DATE        NOT NULL,
    status                  VARCHAR(10) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','COMPLETED','CANCELLED')),
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at            TIMESTAMPTZ,
    cancelled_at            TIMESTAMPTZ,
    cancel_reason           VARCHAR(30) CHECK (cancel_reason IS NULL OR cancel_reason IN ('PROPERTY_SOFT_DELETED','CONTRACT_COMPLETED','CONTRACT_TERMINATED','CONTRACT_RENEWED','CONTRACT_CANCELLED')),
    UNIQUE (property_contract_id, task_type)
);

ALTER TABLE expiry_task
    ADD CONSTRAINT fk_expiry_task_contract_office_property
    FOREIGN KEY (property_contract_id, office_id, property_id, deal_type)
    REFERENCES property_contract (id, office_id, property_id, deal_type)
    ON DELETE RESTRICT;

ALTER TABLE expiry_task
    ADD CONSTRAINT ck_expiry_task_target_date
    CHECK (target_date = contract_end_date - 90);

ALTER TABLE expiry_task ADD CONSTRAINT ck_expiry_task_type CHECK (task_type = 'D90');

ALTER TABLE expiry_task ADD CONSTRAINT ck_expiry_task_status CHECK (
    (status = 'OPEN' AND completed_at IS NULL AND cancelled_at IS NULL AND cancel_reason IS NULL)
    OR (status = 'COMPLETED' AND completed_at IS NOT NULL AND cancelled_at IS NULL AND cancel_reason IS NULL)
    OR (status = 'CANCELLED' AND completed_at IS NULL AND cancelled_at IS NOT NULL AND cancel_reason IS NOT NULL)
);

CREATE INDEX ix_expiry_task_office_status_target ON expiry_task (office_id, status, target_date);

COMMENT ON TABLE expiry_task IS '전세·월세 계약 종료일 90일 전에 생성되는 고객 후속관리 업무. 매매 계약에는 생성하지 않는다';
COMMENT ON COLUMN expiry_task.id IS '업무 내부 식별자';
COMMENT ON COLUMN expiry_task.office_id IS '사무소 ID. property_contract_id·property_id와 함께 대상 계약의 사무소·매물 일치를 복합 외래 키로 검증';
COMMENT ON COLUMN expiry_task.property_id IS '매물 ID. property_contract_id·office_id와 함께 대상 계약을 복합 외래 키로 참조';
COMMENT ON COLUMN expiry_task.property_contract_id IS 'D-90 업무의 기준이 되는 전세·월세 계약';
COMMENT ON COLUMN expiry_task.deal_type IS 'D-90 대상 계약 유형. JEONSE 전세 또는 MONTHLY 월세만 허용하며 참조 계약의 유형과 같아야 한다';
COMMENT ON COLUMN expiry_task.task_type IS '업무 종류(현재는 D90 하나로 고정)';
COMMENT ON COLUMN expiry_task.contract_end_date IS '업무 생성 시점의 계약 종료 예정일 스냅샷';
COMMENT ON COLUMN expiry_task.target_date IS '업무 처리 목표일(만기일 - 90일)';
COMMENT ON COLUMN expiry_task.status IS '업무 상태: OPEN 진행 중, COMPLETED 완료, CANCELLED 취소';
COMMENT ON COLUMN expiry_task.created_at IS '업무 생성 일시(D-90 배치가 생성)';
COMMENT ON COLUMN expiry_task.completed_at IS '업무 완료 처리 일시';
COMMENT ON COLUMN expiry_task.cancelled_at IS '업무 취소 처리 일시';
COMMENT ON COLUMN expiry_task.cancel_reason IS '취소 사유: PROPERTY_SOFT_DELETED 매물 삭제, CONTRACT_COMPLETED 정상 종료, CONTRACT_TERMINATED 중도 종료, CONTRACT_RENEWED 재계약, CONTRACT_CANCELLED 계약 취소';
