COMMENT ON COLUMN property_contract.property_id IS '계약 대상 매물';
COMMENT ON COLUMN property_contract.deal_type IS '계약 유형: SALE 매매, JEONSE 전세, MONTHLY 월세. 대상 매물의 거래 유형과 같아야 한다';
COMMENT ON COLUMN property_contract.previous_contract_id IS '재계약으로 생성된 새 계약이 가리키는 직전 계약. 같은 사무소·매물의 계약만 참조하며 하나의 이전 계약에서 새 계약 하나만 파생될 수 있다';
COMMENT ON COLUMN property_contract.created_by_member_id IS '계약을 등록한 승인된 사무소 구성원';
COMMENT ON COLUMN property_contract.status IS '계약 상태: ACTIVE 계약 중, COMPLETED 정상 종료, TERMINATED 중도 종료, RENEWED 재계약으로 종료, CANCELLED 계약 취소';
COMMENT ON COLUMN property_contract.contract_start_date IS '계약 시작일';
COMMENT ON COLUMN property_contract.contract_end_date IS '계약 종료 예정일. 전세·월세는 필수이고 매매는 NULL이며 전세·월세 D-90 업무의 기준일';
COMMENT ON COLUMN property_contract.owner_party_name IS '매도인·임대인 이름. SALE이면 매도인, JEONSE·MONTHLY이면 임대인';
