-- 계약을 매물과 독립된 이력 엔터티(property_contract)로 분리한다.
-- 배포 전 운영 DB 읽기 전용 사전 조회 결과 property·expiry_task 모두 0행이었으므로
-- 기존 데이터 보존·단계적 전환(expand/contract) 없이 옛 컬럼과 제약을 직접 교체하는
-- 클린 컷오버로 진행한다.

-- expiry_task는 새 구조에서 property_contract를 참조하도록 완전히 바뀌므로
-- 옛 테이블을 먼저 제거한다(운영 데이터 0행 확인됨).
DROP TABLE expiry_task;

-- property: 계약 기간·당사자·금액 컬럼을 제거하고 요약 상태만 남긴다.
ALTER TABLE property DROP CONSTRAINT ck_property_deal_state;
ALTER TABLE property DROP COLUMN has_contract;
ALTER TABLE property DROP COLUMN contract_expiry_date;
ALTER TABLE property DROP COLUMN landlord_name;
ALTER TABLE property DROP COLUMN landlord_phone;
ALTER TABLE property DROP COLUMN current_occupant_name;
ALTER TABLE property DROP COLUMN current_occupant_phone;

ALTER TABLE property ALTER COLUMN property_status SET DEFAULT 'NO_CONTRACT';
ALTER TABLE property ADD UNIQUE (id, office_id, deal_type);

COMMENT ON TABLE property IS '사무소가 관리하는 매물. 계약의 기간·당사자·금액과 과거 이력은 property_contract에 별도로 저장하고, 이 테이블에는 매물 자체 정보와 현재 계약의 요약 상태만 둔다';
COMMENT ON COLUMN property.property_status IS '매물 게시판용 요약 상태: ACTIVE 현재 계약 있음, NO_CONTRACT 현재 계약 없음, NEGOTIATING 전세·월세 계약 종료일이 지났으나 재계약·종료 처리가 끝나지 않아 협의 중. 계약 명령과 D-90 배치가 property_contract와 같은 트랜잭션에서 동기화하며 일반 매물 수정 API로 직접 변경하지 않는다';

-- property_contract: 매매·전세·월세 계약의 현재 상태와 과거 이력을 계약별 행으로 보존한다.
CREATE TABLE property_contract (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    office_id                BIGINT       NOT NULL,
    property_id              BIGINT       NOT NULL,
    deal_type                VARCHAR(10)  NOT NULL CHECK (deal_type IN ('SALE','JEONSE','MONTHLY')),
    previous_contract_id     BIGINT,
    created_by_member_id     BIGINT       NOT NULL,
    status                   VARCHAR(15)  NOT NULL DEFAULT 'ACTIVE'
                                           CHECK (status IN ('ACTIVE','COMPLETED','TERMINATED','RENEWED','CANCELLED')),
    contract_start_date      DATE         NOT NULL,
    contract_end_date        DATE,
    owner_party_name         VARCHAR(50)  NOT NULL,
    owner_party_phone        VARCHAR(20)  NOT NULL,
    counterparty_name        VARCHAR(50)  NOT NULL,
    counterparty_phone       VARCHAR(20)  NOT NULL,
    sale_price               BIGINT,
    deposit_amount           BIGINT,
    monthly_rent_amount      BIGINT,
    ended_at                 TIMESTAMPTZ,
    end_reason               VARCHAR(500),
    created_at               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at               TIMESTAMPTZ  NOT NULL,
    UNIQUE (id, office_id, property_id),
    UNIQUE (id, office_id, property_id, deal_type)
);

ALTER TABLE property_contract
    ADD CONSTRAINT fk_property_contract_property_office_type
    FOREIGN KEY (property_id, office_id, deal_type)
    REFERENCES property (id, office_id, deal_type)
    ON DELETE RESTRICT;

ALTER TABLE property_contract
    ADD CONSTRAINT fk_property_contract_previous_same_property
    FOREIGN KEY (previous_contract_id, office_id, property_id)
    REFERENCES property_contract (id, office_id, property_id)
    ON DELETE RESTRICT;

ALTER TABLE property_contract
    ADD CONSTRAINT fk_property_contract_created_by_membership
    FOREIGN KEY (created_by_member_id, office_id)
    REFERENCES office_membership (member_id, office_id)
    ON DELETE RESTRICT;

ALTER TABLE property_contract ADD CONSTRAINT ck_property_contract_previous_not_self
    CHECK (previous_contract_id IS NULL OR previous_contract_id <> id);

ALTER TABLE property_contract ADD CONSTRAINT ck_property_contract_period CHECK (
    (deal_type = 'SALE' AND contract_end_date IS NULL)
    OR (deal_type IN ('JEONSE','MONTHLY') AND contract_end_date IS NOT NULL
        AND contract_end_date >= contract_start_date)
);

ALTER TABLE property_contract ADD CONSTRAINT ck_property_contract_amounts CHECK (
    (deal_type = 'SALE' AND sale_price IS NOT NULL AND sale_price >= 0
        AND deposit_amount IS NULL AND monthly_rent_amount IS NULL)
    OR (deal_type = 'JEONSE' AND sale_price IS NULL
        AND deposit_amount IS NOT NULL AND deposit_amount >= 0 AND monthly_rent_amount IS NULL)
    OR (deal_type = 'MONTHLY' AND sale_price IS NULL
        AND deposit_amount IS NOT NULL AND deposit_amount >= 0
        AND monthly_rent_amount IS NOT NULL AND monthly_rent_amount >= 0)
);

ALTER TABLE property_contract ADD CONSTRAINT ck_property_contract_status_fields CHECK (
    (status = 'ACTIVE' AND ended_at IS NULL AND end_reason IS NULL)
    OR (status IN ('COMPLETED','RENEWED') AND ended_at IS NOT NULL AND end_reason IS NULL)
    OR (status IN ('TERMINATED','CANCELLED') AND ended_at IS NOT NULL AND end_reason IS NOT NULL)
);

CREATE UNIQUE INDEX uq_property_contract_active
    ON property_contract (property_id) WHERE status = 'ACTIVE';
CREATE UNIQUE INDEX uq_property_contract_previous
    ON property_contract (previous_contract_id) WHERE previous_contract_id IS NOT NULL;
CREATE INDEX ix_property_contract_office_status_start
    ON property_contract (office_id, status, contract_start_date DESC);
CREATE INDEX ix_property_contract_property_created
    ON property_contract (property_id, created_at DESC);

