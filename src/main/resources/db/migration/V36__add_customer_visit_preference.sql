CREATE TABLE customer_visit_preference (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    office_id BIGINT NOT NULL,
    customer_id BIGINT NOT NULL,
    preferred_weekdays VARCHAR(64) NOT NULL DEFAULT '',
    preferred_start_time TIME,
    preferred_end_time TIME,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    retention_until DATE NOT NULL,
    confirmed_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
    CONSTRAINT uq_customer_visit_preference_scope UNIQUE (office_id, customer_id),
    CONSTRAINT fk_customer_visit_preference_customer FOREIGN KEY (customer_id, office_id)
        REFERENCES customer (id, office_id) ON DELETE CASCADE,
    CONSTRAINT ck_customer_visit_preference_time CHECK (
        (preferred_start_time IS NULL AND preferred_end_time IS NULL)
        OR (preferred_start_time IS NOT NULL AND preferred_end_time IS NOT NULL
            AND preferred_start_time < preferred_end_time)
    )
);

