CREATE TABLE app_user (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                       VARCHAR(254),
    password_hash               VARCHAR(255),
    email_verified_at           TIMESTAMPTZ,
    kakao_provider_key          VARCHAR(255),
    kakao_reference_email       VARCHAR(254),
    phone                       VARCHAR(30),
    phone_verified_at           TIMESTAMPTZ,
    name                        VARCHAR(50)  NOT NULL,
    account_status              VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE' CHECK (account_status IN ('ACTIVE','WITHDRAWN')),
    failed_login_count          INT          NOT NULL DEFAULT 0 CHECK (failed_login_count >= 0),
    failed_login_locked_until   TIMESTAMPTZ,
    created_at                  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    withdrawn_at                TIMESTAMPTZ,
    UNIQUE (email),
    UNIQUE (kakao_provider_key)
);

ALTER TABLE app_user ADD CONSTRAINT ck_app_user_withdrawn
    CHECK ((account_status = 'WITHDRAWN') = (withdrawn_at IS NOT NULL));
ALTER TABLE app_user ADD CONSTRAINT ck_app_user_has_login_method
    CHECK (email IS NOT NULL OR kakao_provider_key IS NOT NULL);
ALTER TABLE app_user ADD CONSTRAINT ck_app_user_email_needs_password
    CHECK (email IS NULL OR password_hash IS NOT NULL);

CREATE UNIQUE INDEX uq_app_user_verified_phone
    ON app_user (phone)
    WHERE phone_verified_at IS NOT NULL AND account_status = 'ACTIVE';

CREATE TABLE email_verification_token (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT      REFERENCES app_user(id),
    email           VARCHAR(254) NOT NULL,
    purpose         VARCHAR(10) NOT NULL CHECK (purpose IN ('SIGNUP','LINK','CHANGE')),
    token_hash      CHAR(64)    NOT NULL UNIQUE,
    issued_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at      TIMESTAMPTZ NOT NULL,
    consumed_at     TIMESTAMPTZ,
    superseded_at   TIMESTAMPTZ,
    CHECK (expires_at = issued_at + interval '30 minutes')
);

CREATE UNIQUE INDEX uq_email_verification_active
    ON email_verification_token (email)
    WHERE consumed_at IS NULL AND superseded_at IS NULL;

