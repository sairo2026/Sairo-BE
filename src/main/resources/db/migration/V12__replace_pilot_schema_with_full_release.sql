ALTER TABLE office_registration ADD CONSTRAINT ck_office_registration_status CHECK (
    (status = 'DRAFT'
        AND resulting_office_id IS NULL AND reviewed_at IS NULL AND revoked_at IS NULL AND cancelled_at IS NULL
        AND supplement_reason IS NULL AND rejection_reason IS NULL)
    OR (status = 'PENDING_REVIEW'
        AND resulting_office_id IS NULL AND reviewed_at IS NULL AND revoked_at IS NULL AND cancelled_at IS NULL
        AND supplement_reason IS NULL AND rejection_reason IS NULL)
    OR (status = 'SUPPLEMENT_REQUESTED'
        AND resulting_office_id IS NULL AND revoked_at IS NULL AND cancelled_at IS NULL
        AND supplement_reason IS NOT NULL AND supplement_due_at IS NOT NULL AND rejection_reason IS NULL)
    OR (status = 'APPROVED'
        AND resulting_office_id IS NOT NULL AND reviewed_at IS NOT NULL AND revoked_at IS NULL AND cancelled_at IS NULL
        AND rejection_reason IS NULL)
    OR (status = 'REJECTED'
        AND resulting_office_id IS NULL AND reviewed_at IS NOT NULL AND revoked_at IS NULL AND cancelled_at IS NULL
        AND rejection_reason IS NOT NULL)
    OR (status = 'REVOKED'
        AND resulting_office_id IS NOT NULL AND reviewed_at IS NOT NULL AND revoked_at IS NOT NULL AND cancelled_at IS NULL
        AND revocation_reason IS NOT NULL)
    OR (status = 'CANCELLED'
        AND resulting_office_id IS NULL AND revoked_at IS NULL AND cancelled_at IS NOT NULL)
);

CREATE UNIQUE INDEX uq_office_registration_pending_applicant
    ON office_registration (applicant_user_id)
    WHERE status IN ('DRAFT','PENDING_REVIEW','SUPPLEMENT_REQUESTED');

