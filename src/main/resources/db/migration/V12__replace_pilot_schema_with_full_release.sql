    CHECK (deal_type <> 'SALE' OR lease_period_status IS NULL),
    CHECK (deal_type <> 'SALE' OR contract_status <> 'TERMINATED'),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 1 CHECK (version > 0)
);

