    buyer_tenant_phone                 VARCHAR(30),
    signed_date                        DATE,
    sale_price                         BIGINT,
    deposit_amount                     BIGINT,
    monthly_rent_amount                BIGINT,
    memo                               TEXT CHECK (char_length(memo) <= 2000),
    balance_due_date                   DATE,
    balance_due_date_pending_reason    TEXT CHECK (char_length(balance_due_date_pending_reason) <= 2000),
    payment_amount_mismatch_reason     TEXT,
    lease_start_date                   DATE,
    lease_end_date                     DATE,
    contract_status                    VARCHAR(12)  NOT NULL DEFAULT 'DRAFT'
                                       CHECK (contract_status IN ('DRAFT','SIGNED','ENDED','TERMINATED','CANCELLED','VOID')),
    lease_period_status                VARCHAR(28)
                                       CHECK (lease_period_status IN ('BEFORE_START','IN_PROGRESS','MATURITY_CONFIRMATION_NEEDED')),
