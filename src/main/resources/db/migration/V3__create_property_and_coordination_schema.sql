CREATE TABLE coordination_status_history (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coordination_id        BIGINT      NOT NULL,
    office_id               BIGINT      NOT NULL,
    from_status              VARCHAR(20) CHECK (from_status IS NULL OR from_status IN ('PENDING_RESPONSE','RESPONDED','CONFIRMED','COMPLETED','CANCELLED','NEEDS_REBOOKING')),
    to_status                VARCHAR(20) NOT NULL CHECK (to_status IN ('PENDING_RESPONSE','RESPONDED','CONFIRMED','COMPLETED','CANCELLED','NEEDS_REBOOKING')),
    changed_by_member_id     BIGINT,
    change_source            VARCHAR(20) NOT NULL CHECK (change_source IN ('OFFICE_MEMBER','CUSTOMER_LINK','SYSTEM_BATCH')),
    reason                   TEXT,
    created_at               TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE coordination_status_history
    ADD CONSTRAINT fk_status_history_parent
    FOREIGN KEY (coordination_id, office_id)
    REFERENCES coordination (id, office_id)
    ON DELETE RESTRICT;

ALTER TABLE coordination_status_history
    ADD CONSTRAINT fk_status_history_changed_by_membership
    FOREIGN KEY (changed_by_member_id, office_id) REFERENCES office_membership (member_id, office_id)
    ON DELETE RESTRICT;

ALTER TABLE coordination_status_history ADD CONSTRAINT ck_status_history_actor CHECK (
    (change_source = 'OFFICE_MEMBER' AND changed_by_member_id IS NOT NULL)
    OR (change_source IN ('CUSTOMER_LINK','SYSTEM_BATCH') AND changed_by_member_id IS NULL)
);

CREATE INDEX ix_status_history_coordination_created ON coordination_status_history (coordination_id, created_at);

COMMENT ON TABLE coordination_status_history IS '조율 상태 변경 이력';
COMMENT ON COLUMN coordination_status_history.id IS '이력 내부 식별자';
COMMENT ON COLUMN coordination_status_history.coordination_id IS '대상 조율';
COMMENT ON COLUMN coordination_status_history.office_id IS '비정규화된 사무소 ID(복합 FK로 부모와 일치 검증됨)';
COMMENT ON COLUMN coordination_status_history.from_status IS '변경 전 상태(최초 생성 시 NULL)';
COMMENT ON COLUMN coordination_status_history.to_status IS '변경 후 상태';
COMMENT ON COLUMN coordination_status_history.changed_by_member_id IS '변경을 실행한 사무소 회원(고객이 바꾼 경우 NULL)';
COMMENT ON COLUMN coordination_status_history.change_source IS '변경 출처: OFFICE_MEMBER 사무소 회원, CUSTOMER_LINK 고객 공개링크, SYSTEM_BATCH 시스템 배치';
