CREATE TABLE office_membership_status_history (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    office_membership_id      BIGINT      NOT NULL,
    office_id                 BIGINT      NOT NULL,
    from_status               VARCHAR(10) CHECK (from_status IS NULL OR from_status IN ('PENDING','APPROVED','REJECTED','REVOKED')),
    to_status                 VARCHAR(10) NOT NULL CHECK (to_status IN ('PENDING','APPROVED','REJECTED','REVOKED')),
    changed_by_type           VARCHAR(10) NOT NULL CHECK (changed_by_type IN ('APPLICANT','ADMIN','SYSTEM')),
    changed_by_membership_id  BIGINT,
    reason                    TEXT,
    created_at                TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE office_membership_status_history
    ADD CONSTRAINT fk_membership_history_parent
    FOREIGN KEY (office_membership_id, office_id)
    REFERENCES office_membership (id, office_id)
    ON DELETE RESTRICT;

ALTER TABLE office_membership_status_history
    ADD CONSTRAINT fk_membership_history_changed_by
    FOREIGN KEY (changed_by_membership_id, office_id)
    REFERENCES office_membership (id, office_id)
    ON DELETE RESTRICT;

ALTER TABLE office_membership_status_history ADD CONSTRAINT ck_membership_history_actor CHECK (
    (changed_by_type = 'ADMIN'
        AND changed_by_membership_id IS NOT NULL
        AND (
            changed_by_membership_id != office_membership_id
            OR (from_status = 'APPROVED' AND to_status = 'REVOKED')
        ))
    OR (changed_by_type IN ('APPLICANT','SYSTEM') AND changed_by_membership_id IS NULL)
);

