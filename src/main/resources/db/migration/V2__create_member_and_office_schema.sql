COMMENT ON COLUMN email_verification_code.id IS '인증코드 내부 식별자';
COMMENT ON COLUMN email_verification_code.member_id IS '가입 인증처럼 회원 생성 전 발급된 경우 NULL 가능';
COMMENT ON COLUMN email_verification_code.purpose IS '인증 목적: SIGNUP 가입, LOGIN 로그인, STEP_UP 재인증, EMAIL_CHANGE 이메일 변경';
COMMENT ON COLUMN email_verification_code.target_email IS '코드를 발송한 대상 이메일(소문자 정규화)';
COMMENT ON COLUMN email_verification_code.challenge_id IS '인증 요청 식별자. 코드 제출 시 이 값과 코드를 함께 검증해 요청 컨텍스트를 바인딩';
