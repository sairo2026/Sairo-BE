CREATE UNIQUE INDEX uq_login_identity_active
    ON login_identity (provider, provider_key)
    WHERE revoked_at IS NULL;

COMMENT ON TABLE login_identity IS '로그인 수단(카카오·이메일 연결 정보)';
COMMENT ON COLUMN login_identity.id IS '로그인 수단 내부 식별자';
COMMENT ON COLUMN login_identity.member_id IS '이 로그인 수단을 소유한 회원';
COMMENT ON COLUMN login_identity.provider IS '로그인 제공자: KAKAO 또는 EMAIL';
COMMENT ON COLUMN login_identity.provider_key IS '카카오 고유 회원번호, 또는 정규화(소문자)된 이메일';
COMMENT ON COLUMN login_identity.created_at IS '연결 생성 일시';
COMMENT ON COLUMN login_identity.revoked_at IS '연결 해제(탈퇴) 일시. soft delete — 하드 삭제하지 않음';

