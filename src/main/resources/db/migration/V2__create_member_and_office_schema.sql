CREATE TABLE document_move_outbox (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    office_registration_id  BIGINT      NOT NULL REFERENCES office_registration(id) ON DELETE RESTRICT,
    task_type               VARCHAR(30) NOT NULL CHECK (task_type IN ('MOVE_TO_PENDING_DELETION')),
    status                  VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','IN_PROGRESS','DONE','FAILED')),
    attempt_count           INTEGER     NOT NULL DEFAULT 0,
    next_attempt_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    locked_at               TIMESTAMPTZ,
    locked_by               VARCHAR(100),
    lock_token              UUID,
    lock_expires_at         TIMESTAMPTZ,
    last_error              TEXT,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    processed_at            TIMESTAMPTZ
);

CREATE UNIQUE INDEX uq_document_move_outbox_active
    ON document_move_outbox (office_registration_id, task_type)
    WHERE status IN ('PENDING','IN_PROGRESS');

ALTER TABLE document_move_outbox ADD CONSTRAINT ck_outbox_status CHECK (
    (status = 'PENDING'
        AND locked_at IS NULL AND locked_by IS NULL AND lock_token IS NULL AND lock_expires_at IS NULL
        AND processed_at IS NULL)
    OR (status = 'IN_PROGRESS'
        AND locked_at IS NOT NULL AND locked_by IS NOT NULL AND lock_token IS NOT NULL AND lock_expires_at IS NOT NULL
        AND processed_at IS NULL)
    OR (status = 'DONE'
        AND processed_at IS NOT NULL
        AND locked_at IS NULL AND locked_by IS NULL AND lock_token IS NULL AND lock_expires_at IS NULL)
    OR (status = 'FAILED'
        AND last_error IS NOT NULL
        AND locked_at IS NULL AND locked_by IS NULL AND lock_token IS NULL AND lock_expires_at IS NULL)
);

CREATE INDEX ix_document_move_outbox_due ON document_move_outbox (next_attempt_at) WHERE status = 'PENDING';
CREATE INDEX ix_document_move_outbox_stuck ON document_move_outbox (lock_expires_at) WHERE status = 'IN_PROGRESS';

COMMENT ON TABLE document_move_outbox IS 'S3 증빙서류 이동(반려 시 verified→pending-deletion) 작업 큐(outbox 패턴)';
COMMENT ON COLUMN document_move_outbox.id IS '작업 내부 식별자';
COMMENT ON COLUMN document_move_outbox.office_registration_id IS '대상 신청';
COMMENT ON COLUMN document_move_outbox.task_type IS '작업 종류(현재는 MOVE_TO_PENDING_DELETION 하나)';
COMMENT ON COLUMN document_move_outbox.status IS '작업 상태: PENDING 대기, IN_PROGRESS 처리중, DONE 완료, FAILED 재시도 소진';
COMMENT ON COLUMN document_move_outbox.attempt_count IS '재시도 횟수(일반 카운터, 상한 없음)';
COMMENT ON COLUMN document_move_outbox.next_attempt_at IS '다음 재시도 예정 시각(지수 백오프)';
COMMENT ON COLUMN document_move_outbox.locked_at IS '워커가 lease를 획득한 시각';
COMMENT ON COLUMN document_move_outbox.locked_by IS 'lease를 획득한 워커 인스턴스 식별자';
COMMENT ON COLUMN document_move_outbox.lock_token IS 'lease 획득마다 새로 발급하는 fencing token — 뒤늦게 돌아온 워커의 덮어쓰기 방지';
COMMENT ON COLUMN document_move_outbox.lock_expires_at IS 'lease 만료 시각(만료되면 다른 워커가 회수 가능)';
COMMENT ON COLUMN document_move_outbox.last_error IS '가장 최근 실패 사유(길이 제한 없는 자유 서술)';
COMMENT ON COLUMN document_move_outbox.created_at IS '작업 적재 일시';
COMMENT ON COLUMN document_move_outbox.processed_at IS '작업 완료 일시';

CREATE TABLE office_membership (
    id                                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id                        BIGINT      NOT NULL REFERENCES member(id) ON DELETE RESTRICT,
    office_id                        BIGINT      NOT NULL REFERENCES office(id) ON DELETE RESTRICT,
    role                              VARCHAR(10) NOT NULL CHECK (role IN ('ADMIN','STAFF')),
    status                            VARCHAR(10) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED','REVOKED')),
    created_at                        TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_at                       TIMESTAMPTZ,
    reviewed_by_type                  VARCHAR(10) CHECK (reviewed_by_type IN ('ADMIN','OPERATOR','SYSTEM')),
    reviewed_by_membership_id         BIGINT,
    reviewed_by_operator_identifier   VARCHAR(100),
    rejection_reason                  TEXT,
    revoked_at                        TIMESTAMPTZ,
    revocation_reason                 TEXT,
    UNIQUE (member_id, office_id),
    UNIQUE (id, member_id, office_id),
    UNIQUE (id, office_id)
);

ALTER TABLE office_membership
    ADD CONSTRAINT fk_membership_reviewed_by
    FOREIGN KEY (reviewed_by_membership_id, office_id)
    REFERENCES office_membership (id, office_id)
    ON DELETE RESTRICT;

ALTER TABLE office_membership ADD CONSTRAINT ck_office_membership_reviewer CHECK (
    reviewed_by_type IS NULL
    OR (reviewed_by_type = 'ADMIN'
        AND reviewed_by_membership_id IS NOT NULL AND reviewed_by_operator_identifier IS NULL)
    OR (reviewed_by_type = 'OPERATOR'
        AND reviewed_by_membership_id IS NULL AND reviewed_by_operator_identifier IS NOT NULL)
    OR (reviewed_by_type = 'SYSTEM'
        AND reviewed_by_membership_id IS NULL AND reviewed_by_operator_identifier IS NULL)
);

ALTER TABLE office_membership ADD CONSTRAINT ck_office_membership_status CHECK (
    (status = 'PENDING'
        AND reviewed_at IS NULL AND reviewed_by_type IS NULL
        AND reviewed_by_membership_id IS NULL AND reviewed_by_operator_identifier IS NULL
        AND rejection_reason IS NULL AND revoked_at IS NULL AND revocation_reason IS NULL)
    OR (status = 'APPROVED'
        AND reviewed_at IS NOT NULL AND reviewed_by_type IS NOT NULL
        AND rejection_reason IS NULL AND revoked_at IS NULL AND revocation_reason IS NULL)
    OR (status = 'REJECTED'
        AND reviewed_at IS NOT NULL AND reviewed_by_type IS NOT NULL
        AND rejection_reason IS NOT NULL AND revoked_at IS NULL AND revocation_reason IS NULL)
    OR (status = 'REVOKED'
        AND reviewed_at IS NOT NULL AND reviewed_by_type IS NOT NULL
        AND rejection_reason IS NULL AND revoked_at IS NOT NULL AND revocation_reason IS NOT NULL)
);

CREATE INDEX ix_office_membership_member_status ON office_membership (member_id, status);

