COMMENT ON COLUMN email_verification_code.expires_at IS '만료 시각';
COMMENT ON COLUMN email_verification_code.attempt_count IS '오입력 시도 횟수(0~5). 5에 도달하면 LOCKED로 전환';
COMMENT ON COLUMN email_verification_code.verified_at IS '인증 완료 시각';
COMMENT ON COLUMN email_verification_code.invalidated_at IS 'REPLACED/LOCKED/EXPIRED로 무효화된 시각';
COMMENT ON COLUMN email_verification_code.created_at IS '코드 발급 일시';

