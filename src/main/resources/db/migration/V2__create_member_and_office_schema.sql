CREATE TABLE office_registration (
    id                             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    applicant_member_id            BIGINT       NOT NULL REFERENCES member(id) ON DELETE RESTRICT,
    business_registration_number   VARCHAR(10)  NOT NULL,
    status                         VARCHAR(20)  NOT NULL DEFAULT 'PENDING_VERIFICATION'
                                    CHECK (status IN ('PENDING_VERIFICATION','MANUAL_REVIEW','APPROVED','REJECTED')),
    resulting_office_id            BIGINT       REFERENCES office(id) ON DELETE RESTRICT,
    document_object_key            VARCHAR(500),
    document_original_filename     VARCHAR(255),
    document_mime_type             VARCHAR(50),
    document_size_bytes            BIGINT,
    document_etag                  VARCHAR(64),
    document_checksum_sha256       VARCHAR(64),
    document_storage_status        VARCHAR(20)
                                    CHECK (document_storage_status IN ('VERIFIED','MOVE_PENDING','PENDING_DELETION','DELETED','MOVE_FAILED')),
    rejection_reason                TEXT,
    created_at                     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    reviewed_at                    TIMESTAMPTZ
);

CREATE UNIQUE INDEX uq_office_registration_result
    ON office_registration (resulting_office_id)
    WHERE resulting_office_id IS NOT NULL;

ALTER TABLE office_registration ADD CONSTRAINT ck_office_registration_status CHECK (
    (status IN ('PENDING_VERIFICATION','MANUAL_REVIEW')
        AND resulting_office_id IS NULL AND rejection_reason IS NULL AND reviewed_at IS NULL)
    OR (status = 'APPROVED'
        AND resulting_office_id IS NOT NULL AND rejection_reason IS NULL AND reviewed_at IS NOT NULL)
    OR (status = 'REJECTED'
        AND resulting_office_id IS NULL AND rejection_reason IS NOT NULL AND reviewed_at IS NOT NULL)
);

ALTER TABLE office_registration ADD CONSTRAINT ck_office_registration_storage CHECK (
    status != 'REJECTED'
    OR document_object_key IS NULL
    OR document_storage_status IN ('MOVE_PENDING','PENDING_DELETION','DELETED','MOVE_FAILED')
);

CREATE UNIQUE INDEX uq_office_registration_pending_bizno
    ON office_registration (business_registration_number)
    WHERE status IN ('PENDING_VERIFICATION','MANUAL_REVIEW');

CREATE UNIQUE INDEX uq_office_registration_pending_applicant
    ON office_registration (applicant_member_id)
    WHERE status IN ('PENDING_VERIFICATION','MANUAL_REVIEW');

CREATE INDEX ix_office_registration_bizno_status ON office_registration (business_registration_number, status);

