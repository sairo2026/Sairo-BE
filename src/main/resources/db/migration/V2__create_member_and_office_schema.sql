CREATE TABLE email_verification_code (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id       BIGINT       REFERENCES member(id) ON DELETE SET NULL,
    purpose         VARCHAR(20)  NOT NULL CHECK (purpose IN ('SIGNUP','LOGIN','STEP_UP','EMAIL_CHANGE')),
    target_email    VARCHAR(255) NOT NULL,
    challenge_id    UUID         NOT NULL UNIQUE,
    code_hash       VARCHAR(64)  NOT NULL,
    status          VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE'
                     CHECK (status IN ('ACTIVE','VERIFIED','REPLACED','LOCKED','EXPIRED')),
    expires_at      TIMESTAMPTZ  NOT NULL,
    attempt_count   SMALLINT     NOT NULL DEFAULT 0 CHECK (attempt_count BETWEEN 0 AND 5),
    verified_at     TIMESTAMPTZ,
    invalidated_at  TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

ALTER TABLE email_verification_code ADD CONSTRAINT ck_email_verification_status CHECK (
    (status = 'ACTIVE' AND verified_at IS NULL AND invalidated_at IS NULL)
    OR (status = 'VERIFIED' AND verified_at IS NOT NULL AND invalidated_at IS NULL)
    OR (status IN ('REPLACED','LOCKED','EXPIRED') AND verified_at IS NULL AND invalidated_at IS NOT NULL)
);

CREATE UNIQUE INDEX uq_email_verification_active
    ON email_verification_code (target_email, purpose)
    WHERE status = 'ACTIVE';

