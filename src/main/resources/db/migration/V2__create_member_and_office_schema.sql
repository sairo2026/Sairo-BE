-- 회원, 로그인, 이메일 인증코드, 사무소, 사업자 인증 신청, 문서 이동 outbox, 사무소 소속

CREATE TABLE member (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name        VARCHAR(20)   NOT NULL,
    email                VARCHAR(255)  NOT NULL,
    profile_image_url    VARCHAR(500),
    account_status       VARCHAR(10)   NOT NULL DEFAULT 'ACTIVE'
                          CHECK (account_status IN ('ACTIVE','SUSPENDED','WITHDRAWN')),
    created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    withdrawn_at         TIMESTAMPTZ
);

ALTER TABLE member ADD CONSTRAINT ck_member_withdrawn
    CHECK ((account_status = 'WITHDRAWN') = (withdrawn_at IS NOT NULL));

CREATE UNIQUE INDEX uq_member_email_active
    ON member (email)
    WHERE account_status != 'WITHDRAWN';

COMMENT ON TABLE member IS '회원';
COMMENT ON COLUMN member.id IS '회원 내부 식별자';
COMMENT ON COLUMN member.display_name IS '서비스에서 표시하는 회원 이름';
COMMENT ON COLUMN member.email IS '알림·재인증 코드 수신에 쓰는 가입·연락 이메일(로그인 수단과는 독립)';
COMMENT ON COLUMN member.profile_image_url IS '프로필 이미지 URL';
COMMENT ON COLUMN member.account_status IS '회원 계정 상태: ACTIVE 정상, SUSPENDED 이용 제한, WITHDRAWN 탈퇴';
COMMENT ON COLUMN member.created_at IS '회원 레코드 생성 일시';
COMMENT ON COLUMN member.withdrawn_at IS '탈퇴 처리 일시. WITHDRAWN 상태가 아니면 NULL';

CREATE TABLE login_identity (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id     BIGINT       NOT NULL REFERENCES member(id) ON DELETE RESTRICT,
    provider      VARCHAR(10)  NOT NULL CHECK (provider IN ('KAKAO','EMAIL')),
    provider_key  VARCHAR(255) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    revoked_at    TIMESTAMPTZ
