CREATE TABLE idempotency_record (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    office_id           BIGINT       NOT NULL REFERENCES office(id),
    membership_id       BIGINT       NOT NULL,
    operation           VARCHAR(60)  NOT NULL,
    idempotency_key     VARCHAR(100) NOT NULL,
    request_hash        CHAR(64)     NOT NULL,
    response_status     INT          NOT NULL CHECK (response_status BETWEEN 200 AND 299),
    response_body       JSONB        NOT NULL,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (membership_id, operation, idempotency_key),
    FOREIGN KEY (membership_id, office_id) REFERENCES office_membership (id, office_id)
);

CREATE INDEX ix_idempotency_record_created ON idempotency_record (created_at);

