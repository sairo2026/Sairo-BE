-- A free promotion is an internal service transaction, never a card approval.
CREATE TABLE promotion_campaign (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    code VARCHAR(40) UNIQUE,
    application_starts_at TIMESTAMPTZ NOT NULL,
    application_ends_at TIMESTAMPTZ NOT NULL,
    free_months INTEGER,
    status VARCHAR(12) NOT NULL CHECK (status IN ('DRAFT', 'ACTIVE', 'ENDED')),
    max_offices INTEGER,
    created_by_operator_id BIGINT NOT NULL REFERENCES operator_account(id),
    activated_by_operator_id BIGINT REFERENCES operator_account(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (application_ends_at > application_starts_at),
    CHECK (free_months IS NULL OR free_months BETWEEN 1 AND 120),
    CHECK (max_offices IS NULL OR max_offices > 0),
    CHECK (activated_by_operator_id IS NULL OR activated_by_operator_id <> created_by_operator_id),
    CHECK (status = 'DRAFT' OR activated_by_operator_id IS NOT NULL)
);

ALTER TABLE subscription ADD COLUMN promotion_campaign_id BIGINT
    REFERENCES promotion_campaign(id);
ALTER TABLE subscription DROP CONSTRAINT subscription_check1;
ALTER TABLE subscription ADD CONSTRAINT ck_subscription_free_source
    CHECK (status <> 'TRIAL' OR trial_event_id IS NOT NULL OR promotion_campaign_id IS NOT NULL);

CREATE TABLE promotion_grant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id BIGINT NOT NULL REFERENCES promotion_campaign(id),
    office_id BIGINT NOT NULL REFERENCES office(id),
    subscription_id BIGINT NOT NULL REFERENCES subscription(id),
    status VARCHAR(24) NOT NULL CHECK (status IN ('ACTIVE', 'SUSPENDED', 'RECONCILIATION_REQUIRED', 'CONVERSION_PENDING', 'CANCELLED', 'REVOKED', 'ENDED')),
    starts_at TIMESTAMPTZ NOT NULL,
    free_ends_at TIMESTAMPTZ,
    billing_anchor_at TIMESTAMPTZ NOT NULL,
    next_period_start TIMESTAMPTZ NOT NULL,
    granted_by_operator_id BIGINT NOT NULL REFERENCES operator_account(id),
    ended_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 1,
    UNIQUE (campaign_id, office_id),
    CHECK (free_ends_at IS NULL OR free_ends_at > starts_at),
    CHECK (next_period_start >= starts_at),
    CHECK (version > 0)
);

CREATE UNIQUE INDEX uq_promotion_grant_live_office
    ON promotion_grant (office_id)
    WHERE status IN ('ACTIVE', 'SUSPENDED', 'RECONCILIATION_REQUIRED');
CREATE INDEX ix_promotion_grant_due
    ON promotion_grant (next_period_start)
    WHERE status = 'ACTIVE';

CREATE TABLE promotion_period (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grant_id BIGINT NOT NULL REFERENCES promotion_grant(id),
    office_id BIGINT NOT NULL REFERENCES office(id),
    subscription_id BIGINT NOT NULL REFERENCES subscription(id),
    period_start TIMESTAMPTZ NOT NULL,
    period_end TIMESTAMPTZ NOT NULL,
    list_amount BIGINT NOT NULL CHECK (list_amount >= 0),
    discount_amount BIGINT NOT NULL CHECK (discount_amount >= 0),
    charged_amount BIGINT NOT NULL DEFAULT 0 CHECK (charged_amount = 0),
    price_version VARCHAR(40) NOT NULL,
    member_count_snapshot INTEGER NOT NULL CHECK (member_count_snapshot >= 0),
    office_name_snapshot VARCHAR(100) NOT NULL,
    plan_snapshot VARCHAR(20) NOT NULL,
    record_source VARCHAR(16) NOT NULL DEFAULT 'AUTOMATIC'
        CHECK (record_source IN ('AUTOMATIC', 'RECONCILED')),
    reconciled_by_operator_id BIGINT REFERENCES operator_account(id),
    reconciliation_reason VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (subscription_id, period_start),
    CHECK (period_end > period_start),
    CHECK (discount_amount = list_amount),
    CHECK (record_source = 'AUTOMATIC' OR
        (reconciled_by_operator_id IS NOT NULL AND reconciliation_reason IS NOT NULL))
);

CREATE INDEX ix_promotion_period_office_date
    ON promotion_period (office_id, period_start DESC);
